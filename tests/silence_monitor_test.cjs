const assert=require('node:assert/strict');
const path=require('node:path');
const {SilenceMonitor,rmsFromBytes}=require('../skills/ai-interview/scripts/studio_web/silence_monitor.js');
const silence=new Uint8Array(1024).fill(128);
const speech=new Uint8Array(1024).map((_,i)=> i%2 ? 190 : 66);
assert.equal(rmsFromBytes(silence),0);
assert.ok(rmsFromBytes(speech)>0.45);
let m=new SilenceMonitor({startedAt:0,thresholdMs:40000,rmsThreshold:0.025});
assert.equal(m.sample(0,39999),false);
assert.equal(m.sample(0,40000),true,'initial true silence leads to one check-in');
assert.equal(m.sample(0,85000),false,'no repeat check-in during the same recording');
m=new SilenceMonitor({startedAt:0,thresholdMs:40000,rmsThreshold:0.025});
assert.equal(m.sample(0.12,5000),false);
assert.equal(m.sample(0.12,5500),false);
assert.equal(m.sample(0,42000),false,'confirmed audible speech resets silence clock');
assert.equal(m.sample(0,45500),true);
m=new SilenceMonitor({startedAt:0,thresholdMs:40000,rmsThreshold:0.025});
assert.equal(m.sample(0.2,36000),false);
assert.equal(m.sample(0,40000),true,'single ambient spike must not suppress silence check-in');
assert.equal(m.sample(NaN,40001),false);
console.log('PASS: acoustic silence policy, voice activity reset, once-only, invalid levels');
